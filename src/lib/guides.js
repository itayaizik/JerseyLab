// The plain text of a guide, for the prerendered markup and for anything that
// needs the article without its layout.
export const guideText = (guide) => [
  guide.intro,
  ...guide.sections.flatMap(s => [s.h2, ...(s.paragraphs || []), ...(s.list || [])]),
].join('\n');
